def original_unoptimized_version():
    encryptor = Encryptor()
    plaintext = random.randbytes(16)
    ciphertext = encryptor.encrypt(plaintext=plaintext)
    attackerAES = AES(simplified=True)
    n_rounds = attackerAES.rounds
    keys = []
    for col in range(1, 5):  # 1..4
        for key_guess in tqdm(
            range(2**32),
            desc=f"Finding key for column {col}",
            unit="key guesses",
            miniters=100_000,
            unit_scale=True,
            mininterval=30,
            maxinterval=40,
        ):
            # update key to be used in the encryptiion process
            key = key_guess << ((4 - col) * 32)
            key = attackerAES.KeyFromBytes(key.to_bytes(16, byteorder="big"))
            attackerAES.keys = attackerAES.KeyExpansion(key, rounds=n_rounds)
            c = attackerAES.encrypt(plaintext=plaintext)
            if (c == ciphertext).all():
                # Key found
                keys.append(key)
                break
        else:
            print("Something went REALLY wrong, no key found")
        print_hex(
            sum(keys[col - 1])
        )  # Since we stored the keys shifted, then we just have to sum them to get the final key
    print("Found key:")
    print_hex(
        sum(keys)
    )  # Since we stored the keys shifted, then we just have to sum them to get the final key