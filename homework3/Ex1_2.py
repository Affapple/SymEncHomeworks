def mix_columns_batched(state):
    # state shape: (n keys, 4)
    col = state.astype(np.uint16)
    b = ((col << 1) & 0xFF) ^ (0x1B & -(col >> 7))
    mixed = np.zeros_like(state)
    mixed[:, 0] = b[:, 0] ^ col[:, 3] ^ col[:, 2] ^ b[:, 1] ^ col[:, 1]
    mixed[:, 1] = b[:, 1] ^ col[:, 0] ^ col[:, 3] ^ b[:, 2] ^ col[:, 2]
    mixed[:, 2] = b[:, 2] ^ col[:, 1] ^ col[:, 0] ^ b[:, 3] ^ col[:, 3]
    mixed[:, 3] = b[:, 3] ^ col[:, 2] ^ col[:, 1] ^ b[:, 0] ^ col[:, 0]
    return mixed.astype(np.uint8)


